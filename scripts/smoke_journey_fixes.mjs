import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';

const base = process.env.TPL_LOCAL_TEST_URL || 'http://127.0.0.1:5173';
const output = path.resolve(process.env.TPL_JOURNEY_FIXES_EVIDENCE || '../../reports/interview-lab-2026-11-14/journey-fixes');
const coreOnly = process.env.TPL_JOURNEY_FIXES_PHASE === 'core';
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const checks = [];
const errors = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: 'reduce' });
const page = await context.newPage();
page.setDefaultTimeout(15000);
page.on('pageerror', error=>errors.push(error.message));
const check = (name, condition=true)=>{ assert.ok(condition,name); checks.push(name); console.log(`PASS ${name}`); };
const questionHeading = ()=>page.locator('.survival-question-panel h2');
try {
  await page.goto(`${base}/survival`);
  await page.getByRole('link', {name:'Start Core practice'}).waitFor();
  check('Survival publishes exactly the real Core 20-question / 30-second wave', /20/.test(await page.locator('.grid-3').first().innerText()) && await page.getByRole('link',{name:'Start Core practice'}).count()===1 && !await page.getByText('Intermediate',{exact:true}).count());
  await page.getByRole('link',{name:'Start Core practice'}).click();
  const first = await questionHeading().innerText();
  await page.getByRole('button',{name:'D 0.58',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Correct. d1'}).waitFor();
  check('Correct feedback remains attached to Question 1 until Next', await questionHeading().innerText()===first && /QUESTION 1 \/ 20/.test(await page.locator('.survival-question-panel').innerText()));
  await page.getByRole('button',{name:'Next',exact:true}).click();
  const second = await questionHeading().innerText();
  check('Next advances exactly one question', second!==first && /QUESTION 2 \/ 20/.test(await page.locator('.survival-question-panel').innerText()));
  await page.getByRole('button',{name:'A 6.12',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Correct answer: B.'}).waitFor();
  check('Wrong feedback remains attached to the actual answered price question', await questionHeading().innerText()===second);
  await page.clock.install();
  await page.getByRole('button',{name:'Next',exact:true}).click();
  for (let second=0;second<31;second+=1) await page.clock.runFor(1000);
  await page.getByRole('status').filter({hasText:'Time is up.'}).waitFor();
  check('Timeout removes a life and leaves the question explanation available', /QUESTION 3 \/ 20/.test(await page.locator('.survival-question-panel').innerText()));
  await page.getByRole('button',{name:'Next',exact:true}).click();
  await page.locator('.survival-question-panel button.panel-2').first().click();
  await page.getByRole('button',{name:'Finish run',exact:true}).click();
  await page.getByRole('heading',{name:'Practice run ended',exact:true}).waitFor();
  check('Three-life run ends with truthful answered count and best streak', /4 of 20/.test(await page.locator('main').innerText()) && /x1/.test(await page.locator('main').innerText()));
  await page.clock.resume();
  await page.goto(`${base}/survival/advanced`);
  await page.getByRole('heading',{name:'This wave is not available'}).waitFor();
  check('Direct unavailable-level URL cannot silently open the same question bank', await page.locator('.survival-question-panel').count()===0);
  await page.goto(`${base}/lab/strategies`);
  const condor = page.locator('.grid-3 > .panel').filter({hasText:'Iron Condor'});
  await condor.getByRole('link',{name:'Open payoff builder'}).click();
  await page.locator('[data-payoff-leg-table="true"] tbody tr').first().waitFor();
  check('Iron Condor card opens the actual four-leg strategy', new URL(page.url()).searchParams.get('preset')==='Iron Condor' && await page.locator('[data-payoff-leg-table="true"] tbody tr').count()===4);
  await page.setViewportSize({width:390,height:844});
  await page.goto(`${base}/tools/bs-pricer`);
  const run = page.getByRole('button',{name:'Run pricing analysis',exact:true});
  await run.waitFor();
  const top = await run.evaluate(element=>element.getBoundingClientRect().top+window.scrollY);
  check('Mobile BS action appears within the first 1.5 screens', top<1266);
  check('Engine metadata is a secondary closed disclosure', await page.locator('.tool-contract-disclosure').evaluate(element=>!element.open));
  await page.screenshot({path:path.join(output,'bs-mobile-first-action.png'),fullPage:true});
  await page.route('**/strategy/instruments', route=>route.fulfill({status:503,json:{detail:'Explicit service-state test.'}}));
  await page.goto(`${base}/lab/backtest`);
  await page.getByRole('heading',{name:'Historical research is unavailable'}).waitFor();
  check('Unavailable backtest service has a finite state, disabled run and useful next action', await page.getByRole('button',{name:'Run backtest',exact:true}).isDisabled() && await page.getByRole('link',{name:'Continue interview practice',exact:true}).count()===1 && !/Démarre le backend|uvicorn/.test(await page.locator('main').innerText()));
  await page.getByRole('button',{name:'Retry service',exact:true}).click();
  await page.getByRole('heading',{name:'Historical research is unavailable'}).waitFor();
  check('Backtest connection can be retried without inventing a result', await page.getByRole('button',{name:'Run backtest',exact:true}).isDisabled());
  await page.unroute('**/strategy/instruments');
  if (!coreOnly) {
    await page.setViewportSize({width:1440,height:1000});
    await page.goto(`${base}/courses/black-scholes`);
    const modules = page.locator('.course-lesson-item');
    await modules.nth(2).waitFor();
    await page.getByRole('button',{name:'Resume',exact:true}).waitFor();
    const before = await page.locator('[data-course-completion]').evaluate(element=>element.style.width);
    const desiredTitle = await modules.nth(2).locator('.course-lesson-title').innerText();
    const savedPosition = page.waitForResponse(response=>response.url().includes('/platform/courses/black-scholes/position') && response.request().method()==='PUT');
    await modules.nth(2).click();
    assert.equal((await savedPosition).status(),200);
    check('Changing lessons saves server position without increasing completion', await page.locator('[data-course-completion]').evaluate(element=>element.style.width)===before);
    const freshContext = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
    const fresh = await freshContext.newPage();
    await fresh.goto(`${base}/courses/black-scholes`);
    await fresh.waitForFunction(title=>document.querySelector('.course-lesson-item.active .course-lesson-title')?.textContent===title,desiredTitle);
    check('Fresh browser with no localStorage restores the actual server-owned lesson');
    await fresh.locator('.course-module-formula .katex').first().waitFor();
    check('Parity lesson retains its own formula without a generic BSM proof or unrelated correlation widget', await fresh.locator('.course-equation-demo').count()===0 && await fresh.locator('.lesson-widget-lab [data-ui-block-type="corr_matrix"]').count()===0);
    await fresh.getByRole('button',{name:'Calculator',exact:true}).click();
    const callPrice = fresh.getByText('Call Price',{exact:true}).locator('..').locator(':scope > .mono').first();
    const initialPrice = Number(await callPrice.innerText());
    await fresh.locator('input[type="range"]').first().focus();
    await fresh.keyboard.press('ArrowRight');
    check('The legitimate Black-Scholes course calculator remains interactive', Number(await callPrice.innerText())>initialPrice);
    await fresh.getByRole('button',{name:'Full script',exact:true}).click();
    await fresh.locator('.course-script-shell').first().waitFor();
    const scriptText = await fresh.locator('main').innerText();
    check('Historical HTML comment and masked generic quiz are not rendered', !scriptText.includes('Bloc de quiz générique historique') && !scriptText.includes('<!--'));
    await freshContext.close();
    await page.getByRole('button',{name:'Exercises',exact:true}).click();
    await page.getByRole('link',{name:'Open generator',exact:true}).click();
    await page.getByRole('textbox',{name:'Exercise topic',exact:true}).waitFor();
    check('Course-to-generator preserves topic, product, level and English language', new URL(page.url()).searchParams.get('course')==='black-scholes' && await page.getByRole('textbox',{name:'Exercise topic',exact:true}).inputValue()==='Black-Scholes Model' && await page.getByRole('textbox',{name:'Exercise product',exact:true}).inputValue()==='European vanilla option' && await page.getByRole('combobox',{name:'Exercise difficulty'}).inputValue()==='beginner' && await page.getByRole('combobox',{name:'Exercise language'}).inputValue()==='en');
    await page.screenshot({path:path.join(output,'course-generator-context.png'),fullPage:true});
    await page.setViewportSize({width:390,height:844});
    await page.goto(`${base}/courses/black-scholes`);
    await page.locator('.course-module-list').waitFor();
    check('Mobile module list is collapsed so the current lesson comes first', await page.locator('.course-module-list').evaluate(element=>!element.open));
    const lesson = await page.locator('.course-module-reader h2').first().boundingBox();
    check('Mobile current lesson title is within the first 1.5 screens', lesson.y<1266);
    check('Legacy lesson no longer exposes assembly counters or RAG tabs', !/UI blocks|\d+ mots|RAG sources/.test(await page.locator('main').innerText()));
    await page.screenshot({path:path.join(output,'course-mobile-lesson-first.png'),fullPage:true});
  }
  check('No application runtime errors', errors.length===0);
  await writeFile(path.join(output,coreOnly?'core-results.json':'results.json'),JSON.stringify({verdict:'PASS',checks,errors},null,2));
  console.log(`PASS ${checks.length} real browser journey checks`);
} catch (error) {
  await page.screenshot({path:path.join(output,'failure.png'),fullPage:true}).catch(()=>{});
  await writeFile(path.join(output,'failure.json'),JSON.stringify({checks,errors,error:error.message},null,2));
  throw error;
} finally { await browser.close(); }
