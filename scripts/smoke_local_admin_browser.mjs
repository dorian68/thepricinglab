import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium } from 'playwright';

const base = process.env.TPL_LOCAL_TEST_URL || 'http://127.0.0.1:5173';
const output = path.resolve('../../reports/visual-qa-2026-11-10-local-admin/technical');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ headless: true });
const checks = [];
const errors = [];
const externalApiCalls = [];
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true, reducedMotion: 'reduce' });
await context.route(/https:\/\/(?:[^/]+\.supabase\.co|tpl-api\.optiquant-ia\.com)\//, (route) => { externalApiCalls.push(route.request().url()); return route.abort(); });
const page = await context.newPage();
page.on('pageerror', (error) => errors.push(error.message));
function check(label, condition = true) { assert.ok(condition, label); checks.push(label); console.log(`PASS ${label}`); }
try {
  await page.goto(`${base}/admin`);
  await page.getByText(/forum threads/i, { exact: true }).waitFor({ timeout: 60000 });
  check('fresh browser opens actual admin without credentials');
  await page.reload();
  await page.getByText(/forum threads/i, { exact: true }).waitFor();
  check('admin deep link survives reload');
  await page.goto(`${base}/courses/monte-carlo`);
  const complete = page.getByRole('button', { name: /Mark module complete|Completion saved/ });
  await complete.waitFor();
  if ((await complete.innerText()).includes('Mark module complete')) await complete.click();
  await page.getByRole('button', { name: /Completion saved/ }).waitFor();
  await page.reload();
  await page.getByRole('button', { name: /Completion saved/ }).waitFor();
  check('real lesson completion persists across reload');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: path.join(output, 'course-admin-390.png'), fullPage: true });
  check('mobile test toolbar fits', await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth && document.querySelector('.tpl-preview-toolbar').getBoundingClientRect().right <= window.innerWidth));
  await page.goto(`${base}/tools/bond`);
  await page.getByRole('button', { name: 'Price, solve & measure risk', exact: true }).click();
  await page.locator('[data-bond-results="true"]').waitFor();
  const downloading = page.waitForEvent('download');
  await page.getByRole('button', { name: 'JSON', exact: true }).click();
  const download = await downloading;
  const file = path.join(output, 'bond-test-export.json');
  await download.saveAs(file);
  const bond = JSON.parse(await readFile(file, 'utf8'));
  check('paid bond tool calculates and exports real result', Math.abs(bond.quote.cleanPricePer100 - 100) < 1e-9 && bond.analysisId);
  await page.goto(`${base}/exercises`);
  await page.locator('a.exercise-card').first().click();
  const exercising = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download JSON', exact: true }).click();
  const exercise = await exercising;
  await exercise.saveAs(path.join(output, 'exercise-test-export.json'));
  check('exercise workspace opens and exports');
  await page.getByRole('combobox', { name: 'Rôle de test' }).selectOption('visitor');
  await page.waitForLoadState();
  await page.goto(`${base}/courses/monte-carlo`);
  await page.getByRole('heading', { name: /plan required/ }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: /plan required/ }).waitFor();
  check('visitor choice and locks persist');
  await page.getByRole('combobox', { name: 'Rôle de test' }).selectOption('admin');
  await page.getByRole('button', { name: /Completion saved/ }).waitFor();
  check('returning to admin restores signed access and progress');
  check('no Supabase or online API calls', externalApiCalls.length === 0);
  check('no browser errors', errors.length === 0);

  const failure = await browser.newContext();
  const failed = await failure.newPage();
  await failed.route('**/__dev/session', (route) => route.fulfill({ status: 503, json: { detail: 'Explicit local startup failure test.' } }));
  await failed.goto(`${base}/admin`);
  await failed.getByRole('heading', { name: 'L’espace de test est indisponible' }).waitFor();
  await failed.unroute('**/__dev/session');
  await failed.getByRole('button', { name: 'Réessayer', exact: true }).click();
  await failed.getByText(/forum threads/i, { exact: true }).waitFor();
  check('bootstrap failure explains and retry recovers');
  await failure.close();
  await writeFile(path.join(output, 'results.json'), JSON.stringify({ verdict: 'PASS', checks, errors, externalApiCalls }, null, 2));
  console.log(`PASS ${checks.length} browser checks`);
} finally { await browser.close(); }
